import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

// The catalog is authored exclusively through bun i18n; Android XML is generated.
const messages = resolve(import.meta.dir, '../../web/src/messages')
const resources = resolve(import.meta.dir, '../app/src/main/res')
const check = Bun.argv.includes('--check')
const escapeXml = (value: string) =>
  value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll("'", "\\'")
    .replaceAll('"', '\\"')
type Catalog = { AndroidNative?: Record<string, string> }
const baseline: Catalog = JSON.parse(
  await readFile(resolve(messages, 'en-US.json'), 'utf8'),
)
for (const filename of (await readdir(messages)).filter((name) =>
  name.endsWith('.json'),
)) {
  const locale = filename.slice(0, -5)
  const catalog: Catalog = JSON.parse(
    await readFile(resolve(messages, filename), 'utf8'),
  )
  // Sparse overlays inherit from their actual parent, then en-US.
  const parent: Catalog =
    locale === 'pt-BR'
      ? JSON.parse(await readFile(resolve(messages, 'pt.json'), 'utf8'))
      : {}
  const strings = {
    ...baseline.AndroidNative,
    ...parent.AndroidNative,
    ...catalog.AndroidNative,
  }
  const directory =
    locale === 'en-US'
      ? 'values'
      : locale === 'he'
        ? 'values-iw'
        : locale === 'id'
          ? 'values-in'
          : `values-b+${locale.replaceAll('-', '+')}`
  const path = resolve(resources, directory, 'strings.xml')
  const lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by the Android sync:strings command. Edit catalogs via bun i18n. -->',
    '<resources>',
  ]
  if (locale === 'en-US') {
    lines.push(
      '    <string name="app_name" translatable="false">Spliit Cloud</string>',
    )
    lines.push(
      '    <string name="asset_statements" translatable="false">[{\\"relation\\":[\\"delegate_permission/common.handle_all_urls\\"],\\"target\\":{\\"namespace\\":\\"web\\",\\"site\\":\\"https://spliit.cloud\\"}}]</string>',
    )
  }
  for (const [key, value] of Object.entries(strings).sort(([a], [b]) =>
    a.localeCompare(b),
  )) {
    let text = value
      .replaceAll('%', '%%')
      .replaceAll('{version}', '%1$s')
      .replaceAll('{code}', '%2$d')
    if (/\{[^}]+\}/.test(text))
      throw new Error(`Unsupported native placeholder in ${locale}.${key}`)
    lines.push(`    <string name="${key}">${escapeXml(text)}</string>`)
  }
  lines.push('</resources>', '')
  const output = lines.join('\n')
  if (check) {
    const current = await readFile(path, 'utf8').catch(() => '')
    if (current !== output)
      throw new Error(`Run sync:strings: ${path} is stale`)
  } else {
    await mkdir(resolve(resources, directory), { recursive: true })
    await writeFile(path, output)
  }
}
